window.careText = function (field, varietyKey) {
  if (field == null) return "";
  if (typeof field === "string") return field;
  var v = varietyKey || window.CARE_GUIDE.defaultVariety;
  if (field[v] != null) return field[v];
  var fb = window.CARE_GUIDE.defaultVariety;
  return field[fb] != null ? field[fb] : "";
};

