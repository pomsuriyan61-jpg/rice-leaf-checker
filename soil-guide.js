// แปลผลอาหารของต้นข้าวรายตัว คืน null ถ้าไม่มีค่าหรือไม่รู้จักธาตุนั้น
window.readNutrient = function (key, value) {
  if (typeof value !== "number" || isNaN(value)) return null;
  var list = window.SOIL_GUIDE.nutrients || [];
  for (var i = 0; i < list.length; i++) {
    if (list[i].key !== key) continue;
    var bands = list[i].bands;
    for (var j = 0; j < bands.length; j++) {
      if (value < bands[j].max) {
        // คืนข้อมูลธาตุมาด้วย ฝั่งเรียกใช้จะได้ไม่ต้องค้นซ้ำ
        return { nutrient: list[i], band: bands[j] };
      }
    }
    return { nutrient: list[i], band: bands[bands.length - 1] };
  }
  return null;
};

// คืนการแปลผล pH ตามช่วงค่า ถ้าไม่มีค่าให้คืน null (ฝั่งเรียกใช้ต้องเช็คเอง)
window.readSoilPh = function (ph) {
  if (typeof ph !== "number" || isNaN(ph)) return null;
  var bands = window.SOIL_GUIDE.phBands;
  for (var i = 0; i < bands.length; i++) {
    if (ph < bands[i].max) return bands[i];
  }
  return bands[bands.length - 1];
};
