// คืนการแปลผล pH ตามช่วงค่า ถ้าไม่มีค่าให้คืน null (ฝั่งเรียกใช้ต้องเช็คเอง)
window.readSoilPh = function (ph) {
  if (typeof ph !== "number" || isNaN(ph)) return null;
  var bands = window.SOIL_GUIDE.phBands;
  for (var i = 0; i < bands.length; i++) {
    if (ph < bands[i].max) return bands[i];
  }
  return bands[bands.length - 1];
};
