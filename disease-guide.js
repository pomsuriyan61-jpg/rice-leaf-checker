// ============================================================
// ตัวค้นหาข้อมูลโรคแบบทนต่อความต่างของชื่อ label
// ============================================================
//
// ทำไมต้องมี: ทุกครั้งที่เทรนโมเดลใหม่ ชื่อ label มักเปลี่ยนไปเล็กน้อย
// ("Brown spot" → "brownspot") ซึ่งเดิมจะทำให้การ์ดแนวทางแก้ไขหายไปเงียบๆ
// ฟังก์ชันนี้ตัดปัญหานั้นทิ้ง โดยเทียบชื่อแบบ normalize แล้ว
//
// ผลข้างเคียงที่ต้องรู้: index ถูกสร้างครั้งเดียวตอนโหลดไฟล์
// ถ้าแก้ window.DISEASE_GUIDE ตอน runtime ต้องเรียก window.rebuildDiseaseIndex() ใหม่
(function () {
  "use strict";

  // ตัดทุกอย่างที่ไม่ใช่ตัวอักษร/ตัวเลข แล้วลดเป็นตัวพิมพ์เล็ก
  // "Brown spot" / "brown_spot" / "BROWNSPOT" → "brownspot" เหมือนกันหมด
  function normalizeLabel(s) {
    return String(s == null ? "" : s).toLowerCase().replace(/[^a-z0-9\u0E00-\u0E7F]/g, "");
  }

  var index = {};

  function rebuild() {
    index = {};
    var guide = window.DISEASE_GUIDE || {};
    Object.keys(guide).forEach(function (key) {
      var entry = guide[key];
      if (!entry) return;

      // ชื่อทั้งหมดที่ควรชี้มาที่ข้อมูลก้อนนี้: key หลัก + ชื่อสำรอง + ชื่อไทย
      var names = [key].concat(entry.aliases || []);
      if (entry.thai) names.push(entry.thai);

      names.forEach(function (name) {
        var k = normalizeLabel(name);
        // ไม่เขียนทับของเดิม เพื่อให้ key หลักชนะ alias เสมอเมื่อชนกัน
        if (k && !index[k]) index[k] = entry;
      });
    });
    return index;
  }

  rebuild();

  window.rebuildDiseaseIndex = rebuild;
  window.normalizeDiseaseLabel = normalizeLabel;

  // คืนข้อมูลโรคจากชื่อ label ใดก็ได้ ถ้าไม่พบคืน null (ไม่ throw)
  // ฝั่งเรียกใช้ต้องเช็ค null เองเสมอ เพราะโมเดลอาจส่งคลาสที่ยังไม่มีข้อมูลมา
  window.findDiseaseGuide = function (label) {
    if (!label) return null;
    return index[normalizeLabel(label)] || null;
  };

  // รายชื่อคลาสที่โมเดลปัจจุบันควรส่งมา — ใช้เช็คว่าข้อมูลครบไหมตอนเปิดเว็บ
  // ถ้าโมเดลส่งคลาสที่ไม่มีในฐานความรู้ จะเตือนใน console ให้เห็นตั้งแต่ตอนพัฒนา
  // ดีกว่าปล่อยให้ไปเจอตอนสาธิตหน้างาน
  window.auditDiseaseLabels = function (modelLabels) {
    var missing = (modelLabels || []).filter(function (l) { return !window.findDiseaseGuide(l); });
    if (missing.length) {
      console.warn("[disease-guide] โมเดลมีคลาสที่ยังไม่มีข้อมูลในฐานความรู้:", missing);
    }
    return missing;
  };
})();
